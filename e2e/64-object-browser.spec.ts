test('selection candidates respect assembly visibility and object selection reveals the part', async ({ page }) => {
  await openApp(page)
  await loadParts(page)
  await page.evaluate(() => {
    const tool = (window as any).__aluframe.tool.getState()
    tool.setBuildStep(0)
    tool.setFrameSelectRect({x1: 0, y1: 0, x2: 2000, y2: 2000})
  })
  await expect.poll(async () => (await store(page)).selectedIds.length).toBeLessThan(2)
  await page.getByTestId('sidebar-tab-objects').click()
  await page.evaluate(() => (window as any).__aluframe.tool.getState().setSection({ axis: 'x', at: 9000, flip: false }))
  await page.getByTestId('object-row').filter({ hasText: 'P-second' }).getByRole('button').first().click()
  expect(await page.evaluate(() => {
    const tool = (window as any).__aluframe.tool.getState()
    return {step: tool.buildStep, section: tool.section}
  })).toEqual({step:null, section:null})
  expect((await store(page)).selectedIds).toEqual(['second'])
})

test('persistent groups select all members, survive undo and copy with fresh IDs', async ({ page }) => {
  await openApp(page)
  await loadParts(page)
  await page.getByTestId('sidebar-tab-objects').click()
  await page.getByTestId('object-row').first().getByRole('button').first().click()
  await page.getByTestId('object-row').nth(1).getByRole('button').first().click({ modifiers: ['Shift'] })
  await page.getByTestId('group-create').click()
  await page.getByRole('textbox', { name: '组名称', exact: true }).fill('左框')
  await page.getByRole('button', { name: '确定', exact: true }).click()
  const groups = page.getByTestId('object-group')
  await expect(groups).toHaveCount(1)
  await page.getByTitle('隐藏选中对象', { exact: true }).click()
  await page.getByTestId('object-search').fill('nothing')
  await groups.first().getByRole('button').first().click()
  expect((await store(page)).selectedIds).toEqual(['first', 'second'])
  await expect(page.getByTestId('object-search')).toHaveValue('')
  await expect(page.getByTestId('object-row').filter({ hasText: 'P-first' })).not.toHaveClass(/is-hidden/)
  await groups.first().getByTitle('重命名组', { exact: true }).click()
  await page.getByRole('textbox', { name: '组名称', exact: true }).fill('侧框')
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await expect(groups.first()).toContainText('侧框')
  // Move focus out of the name form before exercising editor shortcuts.
  await page.getByTestId('sidebar-tab-objects').click()
  await page.keyboard.press('Control+c')
  await page.keyboard.press('Control+v')
  await expect(groups).toHaveCount(2)
  const metadata = await page.evaluate(() => (window as any).__aluframe.store.getState().groups)
  expect(metadata[1].name).toBe('侧框')
  expect(metadata[1].id).not.toBe(metadata[0].id)
  expect(metadata[1].memberIds.every((id: string) => !metadata[0].memberIds.includes(id))).toBe(true)
  await page.keyboard.press('Control+z')
  await expect(groups).toHaveCount(1)
  await groups.first().getByTitle('解散组，保留零件', { exact: true }).click()
  await expect(groups).toHaveCount(0)
  expect((await store(page)).profiles).toHaveLength(2)
  await page.keyboard.press('Control+z')
  await expect(groups).toHaveCount(1)
  await page.evaluate(() => (window as any).__aluframe.tool.setState({ viewMode: true }))
  await expect(groups.first().getByTitle('重命名组', { exact: true })).toBeDisabled()
  await expect(groups.first().getByTitle('解散组，保留零件', { exact: true })).toBeDisabled()
})
