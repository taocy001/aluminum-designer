import { test, expect } from '@playwright/test'
import { openApp, store, w2c } from './helpers'

async function loadParts(page: import('@playwright/test').Page) {
  await page.evaluate(() => {
    const profile = (id: string, x: number) => ({ id, spec: '2020', length: 500, position: [x, 100, 0], quaternion: [0, 0, 0, 1], holes: [], miterCuts: [] })
    const api = (window as any).__aluframe
    api.store.getState().loadDocument({ profiles: [profile('first', 0), profile('second', 300)], connectors: [], panels: [], fittings: [], equipment: [] })
    api.tool.getState().putDown()
  })
}

test('object search, Shift selection, isolation and restore preserve document and history', async ({ page }) => {
  await openApp(page)
  await loadParts(page)
  const before = await store(page)
  await page.getByTestId('sidebar-tab-objects').click()
  const first = page.getByTestId('object-row').filter({ hasText: 'P-first' })
  const second = page.getByTestId('object-row').filter({ hasText: 'P-second' })
  await first.getByRole('button').first().click()
  await second.getByRole('button').first().click({ modifiers: ['Shift'] })
  expect((await store(page)).selectedIds).toEqual(['first', 'second'])
  await expect(page.getByTestId('sidebar-tab-objects')).toHaveAttribute('aria-selected', 'true')
  await first.getByRole('button').first().click()
  await page.getByTitle('只显示选中对象', { exact: true }).click()
  await expect(second).toHaveClass(/is-hidden/)
  const sceneIds = () => page.evaluate(() => { const ids: string[] = []; (window as any).__aluframe.sceneRoot.traverse((o: any) => { if (o.userData.profileId) ids.push(o.userData.profileId) }); return [...new Set(ids)] })
  await expect.poll(sceneIds).not.toContain('second')
  const point = await w2c(page, [300, 100, 250])
  expect(await page.evaluate(p => (window as any).__aluframe.pickAt(p.x, p.y).some((h: any) => h.id === 'second'), point)).toBe(false)
  await page.getByTitle('恢复全部可见', { exact: true }).click()
  await expect.poll(sceneIds).toContain('second')
  await page.getByTestId('object-search').fill('2020')
  await expect(page.getByTestId('object-row')).toHaveCount(2)
  await page.getByTestId('object-search').fill('P-second')
  await expect(page.getByTestId('object-row')).toHaveCount(1)
  const after = await store(page)
  expect(after.profiles).toEqual(before.profiles)
  expect(after.past).toBe(before.past)
})

